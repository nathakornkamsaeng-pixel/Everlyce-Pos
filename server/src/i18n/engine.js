function builtInTranslations() {
  const map = {};
  for (const [source, th] of Object.entries(PHRASEBOOK)) {
    map[source] = th;
    const title = source.replace(/\b\w/g, (character) => character.toUpperCase());
    map[title] = th;
  }
  for (const source of UI_STRINGS) {
    const th = lookupLocal(source);
    if (th) map[source] = th;
  }
  return map;
}

