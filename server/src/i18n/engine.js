// Tokens that must survive translation untouched (size codes, currency, numbers).
const PROTECTED = /^(?:[XLMS]{1,4}|[0-9][0-9.,]*|[A-Z]{2,4}(?:\/[A-Z]{2,4})?)$/;

function isProtectedToken(token) {
  return PROTECTED.test(token);
}

function isOnlyProtected(text) {
  const tokens = String(text).trim().split(/\s+/).filter(Boolean);
  return tokens.length > 0 && tokens.every(isProtectedToken);
}

// Replace protected tokens with placeholders so the engine cannot alter them.
function mask(text) {
  const found = [];
  const masked = String(text).replace(/\b([A-Za-z0-9][A-Za-z0-9.,/]*)\b/g, (m) => {
    if (!isProtectedToken(m)) return m;
    const token = `ZXQ${found.length}QXZ`;
    found.push(m);
    return token;
  });
  return { masked, found };
}

function unmask(text, found) {
  let out = String(text);
  found.forEach((original, i) => {
    out = out.replace(new RegExp(`ZXQ${i}QXZ`, 'g'), original);
  });
  return out;
}

function decodeEntities(text) {
  return String(text)
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&amp;/g, '&')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>');
}

function lookupLocal(text) {
  const key = String(text).trim().toLowerCase().replace(/\s+/g, ' ');
  if (PHRASEBOOK[key]) return PHRASEBOOK[key];
  const title = key.replace(/\b\w/g, (c) => c.toUpperCase());
  if (PHRASEBOOK[title]) return PHRASEBOOK[title];
  return null;
}

async function translateOnline(text) {
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), REQUEST_TIMEOUT);
  try {
    const url = `${ONLINE_ENDPOINT}?q=${encodeURIComponent(text)}&langpair=en|th`;
    const res = await fetch(url, { signal: controller.signal });
    if (!res.ok) return null;
    const data = await res.json();
    if (!data || data.responseStatus !== 200 || data.quotaFinished) return null;
    const translated = data.responseData && data.responseData.translatedText;
    if (!translated) return null;
    const cleaned = decodeEntities(translated).trim();
    if (!cleaned || cleaned.toLowerCase() === String(text).trim().toLowerCase()) return null;
    return cleaned;
  } catch (e) {
    return null;
  } finally {
    clearTimeout(timer);
  }
}

// Returns { text, status, origin, skipped }
async function translate(text) {
  const source = String(text == null ? '' : text).trim();
  if (!source) return { text: '', status: 'skipped', origin: 'none', skipped: true };

  // Pure size codes / numbers are published as-is, never sent anywhere.
  if (isOnlyProtected(source)) {
    return { text: source, status: 'skipped', origin: 'protected', skipped: true };
  }

  const { masked, found } = mask(source);

  const local = lookupLocal(source);
  if (local) {
    return { text: unmask(local, found), status: 'draft', origin: 'local', skipped: false };
  }

  const online = await translateOnline(masked);
  if (online) {
    return { text: unmask(online, found), status: 'draft', origin: 'engine', skipped: false };
  }

  return { text: source, status: 'missing', origin: 'fallback', skipped: false };
}

